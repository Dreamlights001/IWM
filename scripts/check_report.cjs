const fs = require('fs');
const path = require('path');
const assert = require('assert');
const { chromium } = require('/home/dlts/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const root = path.resolve(__dirname, '..');
const expectedPapers=JSON.parse(fs.readFileSync(path.join(root,'papers/manifest.json'),'utf8')).length;
const url = 'file://' + path.join(root, 'report.html');
(async()=>{
  const browser = await chromium.launch({headless:true,args:['--no-sandbox']});
  const page = await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
  const errors=[], requests=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(r.url().startsWith('http'))requests.push(r.url())});
  await page.goto(url);await page.evaluate(()=>document.fonts.ready);
  await page.screenshot({path:path.join(root,'qa/desktop-cover.png')});
  await page.locator('#machine').scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(root,'qa/desktop-machine.png')});
  await page.evaluate(()=>document.querySelector('#deformation').scrollIntoView({block:'start',behavior:'instant'}));
  await page.screenshot({path:path.join(root,'qa/desktop-deformation.png')});
  await page.locator('#route-jepa').scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(root,'qa/desktop-jepa.png')});
  const manifest=JSON.parse(fs.readFileSync(path.join(root,'papers/manifest.json'),'utf8'));
  const familyCount=f=>manifest.filter(r=>r.family===f).length;
  await page.locator('#paper-family').selectOption('cutting');
  assert.equal(await page.locator('.paper:visible').count(),familyCount('cutting'));
  await page.locator('#reset-filter').click();
  await page.locator('#paper-search').fill('PointWorld');
  assert.equal(await page.locator('.paper:visible').count(),1);
  assert.equal(await page.locator('.paper:visible').getAttribute('id'),'ref-P44');
  await page.locator('#reset-filter').click();
  await page.locator('#paper-family').selectOption('jepa');
  assert.equal(await page.locator('.paper:visible').count(),familyCount('jepa'));
  await page.evaluate(()=>{location.hash='ref-P23'});await page.waitForTimeout(150);
  assert.equal(await page.locator('.paper:visible').count(),expectedPapers);
  assert(await page.locator('#ref-P23').isVisible());
  await page.screenshot({path:path.join(root,'qa/desktop-papers.png')});
  const desktop=await page.evaluate(()=>({viewport:innerWidth,width:document.documentElement.scrollWidth,height:document.documentElement.scrollHeight,papers:document.querySelectorAll('.paper').length}));
  assert(desktop.width<=desktop.viewport);
  await page.setViewportSize({width:390,height:844});await page.goto(url);
  await page.screenshot({path:path.join(root,'qa/mobile-cover.png')});
  await page.locator('#machine').scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(root,'qa/mobile-machine.png')});
  await page.evaluate(()=>document.querySelector('#deformation').scrollIntoView({block:'start',behavior:'instant'}));
  await page.screenshot({path:path.join(root,'qa/mobile-deformation.png')});
  const mobile=await page.evaluate(()=>({viewport:innerWidth,width:document.documentElement.scrollWidth,height:document.documentElement.scrollHeight}));
  assert(mobile.width<=mobile.viewport);
  await page.emulateMedia({media:'print'});await page.setViewportSize({width:794,height:1123});await page.goto(url);
  await page.locator('#comparison').scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(root,'qa/print-style.png')});
  const print=await page.evaluate(()=>({viewport:innerWidth,width:document.documentElement.scrollWidth}));
  assert(print.width<=print.viewport);
  const nojs=await browser.newPage({javaScriptEnabled:false});await nojs.goto(url);
  assert.equal(await nojs.locator('.paper:visible').count(),expectedPapers);
  assert.equal(errors.length,0);assert.equal(requests.length,0);
  const now=new Date();
  const today=`${now.getFullYear()}-${String(now.getMonth()+1).padStart(2,'0')}-${String(now.getDate()).padStart(2,'0')}`;
  const result={checked_at:today,desktop,mobile,print,js_errors:errors,external_loads:requests,paper_search:true,category_filter:true,citation_reveals_filtered_reference:true,no_js_all_papers_visible:true,print_check:'CSS screenshot only; no paginated PDF generated'};
  fs.writeFileSync(path.join(root,'qa/browser-checks.json'),JSON.stringify(result,null,2));
  console.log(JSON.stringify(result,null,2));await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
